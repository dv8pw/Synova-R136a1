function cloneValues(value) {
  if (Array.isArray(value)) return value.map(cloneValues);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, nested]) => [key, cloneValues(nested)]));
  }
  return value;
}

function mergeValues(target, overrides) {
  for (const [key, value] of Object.entries(overrides)) {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      target[key] = mergeValues(target[key] || {}, value);
    } else {
      target[key] = value;
    }
  }
  return target;
}

function defineTheme(id, name, overrides = {}) {
  return mergeValues({ id, name, ...cloneValues(originalDesign) }, overrides);
}

